/** Some packages ship a LICENSE file but no "license" field. Recognise the common texts by their first lines. */
function licenceFromFile(dir) {
  const name = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f))
  if (!name) return null
  const head = readFileSync(join(dir, name), 'utf8').slice(0, 600)
  if (/MIT License|Permission is hereby granted, free of charge/i.test(head)) return 'MIT'
  if (/Apache License\s+Version 2\.0/i.test(head)) return 'Apache-2.0'
  if (/ISC License|Permission to use, copy, modify, and\/or distribute/i.test(head)) return 'ISC'
  if (/BSD 3-Clause/i.test(head)) return 'BSD-3-Clause'
  if (/BSD 2-Clause/i.test(head)) return 'BSD-2-Clause'
  return null
}

function addLibrary(name, dir, kind, via) {
  if (seen.has(dir)) return seen.get(dir)
  const pj = readJson(join(dir, 'package.json'))
  let licence = spdx(pj)
  let licenceFrom = 'package.json'
  if (!licence) {
    licence = licenceFromFile(dir)
    licenceFrom = licence ? 'LICENSE file (package.json has no licence field)' : null
  }
  const entry = {
    name: pj.name ?? name,
    version: pj.version ?? null,
    licence,
    open: isOpen(licence),
    ...(licenceFrom && licenceFrom !== 'package.json' ? { licenceFrom } : {}),
    kind,
    direct: via === null,
    ...(via ? { via } : {}),
    ...(via === null ? { use: USE[name] ?? (name.startsWith('d3-') ? 'chart maths' : null), importedInSrc: imported(name) } : {}),
    url: repoUrl(pj),
  }
  seen.set(dir, entry)
  libraries.push(entry)
  if (!licence) flag('blocker', `npm: ${entry.name}@${entry.version}`, 'no licence field in its package.json and no recognisable LICENSE file', 'read its licence by hand or remove the package')
  else if (entry.licenceFrom) flag('note', `npm: ${entry.name}@${entry.version}${via ? ` (via ${via})` : ''}`, `package.json has no licence field; its LICENSE file is ${licence}`, 'none')
  else if (!entry.open) flag('review', `npm: ${entry.name}@${entry.version}`, `licence "${licence}" is not on the open list in gen-credits.mjs`, 'check the licence text; add it to OPEN if it is OSI-approved')
  return entry
}

function walkDeps(dir, kind, via) {
  const pj = readJson(join(dir, 'package.json'))
  for (const dep of Object.keys(pj.dependencies ?? {})) {
    const d = resolvePkg(dep, dir)
    if (!d) continue // optional platform packages that are not installed
    if (seen.has(d)) continue
    addLibrary(dep, d, kind, via)
    walkDeps(d, kind, via)
  }
}

