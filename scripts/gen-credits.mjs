function spdx(pj) {
  let l = pj.license ?? pj.licenses
  if (Array.isArray(l)) l = l.map((x) => (typeof x === 'string' ? x : x?.type)).filter(Boolean).join(' OR ')
  if (l && typeof l === 'object') l = l.type
  return typeof l === 'string' && l.trim() ? l.trim() : null
}

/** true when every licence in an "AND" list, or at least one in an "OR" list, is in OPEN. */
function isOpen(expr) {
  if (!expr) return false
  const clean = expr.replace(/[()]/g, ' ').trim()
  if (/\bOR\b/i.test(clean)) return clean.split(/\s+OR\s+/i).some((part) => isOpen(part))
  return clean.split(/\s+AND\s+/i).every((id) => OPEN.has(id.trim()))
}

/** Find node_modules/<name> the way Node does: nearest first, walking up from the package that asks. */
function resolvePkg(name, fromDir) {
  let dir = fromDir
  for (;;) {
    const cand = join(dir, 'node_modules', name, 'package.json')
    if (existsSync(cand)) return dirname(cand)
    const up = dirname(dir)
    if (up === dir || !dir.startsWith(APP)) return null
    dir = up
  }
}

const repoUrl = (pj) => {
  const r = typeof pj.repository === 'string' ? pj.repository : pj.repository?.url
  if (!r) return pj.homepage ?? null
  const url = r.replace(/^git\+/, '').replace(/^git:\/\//, 'https://').replace(/^github:/, 'https://github.com/').replace(/\.git$/, '')
  return /^[\w.-]+\/[\w.-]+$/.test(url) ? `https://github.com/${url}` : url // "owner/repo" shorthand
}

