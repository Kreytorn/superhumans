// Dev-only: drives prototype A like a judge would (click, keyboard, touch) and prints what changed.
//   node src/protos/A/_check.mjs <out dir>      (dev server on :5201)
import { chromium } from 'playwright-core'
const base = 'http://localhost:5201/#/proto/A/'
const out = process.argv[2]
const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--hide-scrollbars', '--force-device-scale-factor=1'] })
const logs = []
async function ctx(w, h, touch) {
  const c = await browser.newContext({ viewport: { width: w, height: h }, deviceScaleFactor: 1, hasTouch: touch, isMobile: touch })
  const p = await c.newPage()
  p.on('console', (m) => {
    if (m.type() === 'error') logs.push(`[${w}] ${m.text()}`)
  })
  p.on('pageerror', (e) => logs.push(`[${w}] pageerror ${e.message}`))
  return p
}
const root = (p) =>
  p.evaluate(() => {
    const r = document.querySelector('.vb')
    return r ? { view: r.dataset.view, state: r.dataset.state, ready: r.dataset.ready, source: r.dataset.source ?? null, hash: location.hash } : null
  })
const ready = (p) => p.waitForSelector('.vb[data-ready="1"]', { timeout: 20000 })
const flat = (s) => s.replace(/\s+/g, ' ')

// ---- laptop
let p = await ctx(1440, 900, false)
await p.goto(base + 'home')
await ready(p)
await p.waitForTimeout(600)
await p.screenshot({ path: `${out}/home_drawing_1440.png` })
await p.click('[data-qa="primary"]')
await p.waitForTimeout(200)
await p.screenshot({ path: `${out}/pull_200ms_1440.png` })
await p.waitForTimeout(700)
console.log('home -> blood', await root(p))
await p.click('[data-qa="primary"]')
await p.waitForTimeout(300)
console.log('pressed', await root(p), flat(await p.locator('.vb-edge').innerText()))
await p.waitForSelector('.vb[data-state="result"]', { timeout: 60000 }).catch(() => logs.push('no result state within 60 s'))
console.log('settled', await root(p), '|', flat(await p.locator('.vb-edge').innerText()), '|', flat(await p.locator('.vb-result').innerText()))
await p.screenshot({ path: `${out}/live_result_1440.png` })
await p.focus('.vb-photo')
await p.keyboard.press('ArrowRight')
await p.keyboard.press('ArrowRight')
for (let i = 0; i < 12; i++) await p.keyboard.press('ArrowRight')
console.log('cell picked by keyboard:', flat(await p.locator('.vb-loupe').innerText()))
await p.waitForTimeout(250)
await p.screenshot({ path: `${out}/loupe_keyboard_1440.png` })
await p.mouse.move(520, 640)
await p.waitForTimeout(250)
console.log('cell picked by mouse:', flat(await p.locator('.vb-loupe').innerText().catch(() => 'no loupe')))
await p.screenshot({ path: `${out}/loupe_mouse_1440.png` })
await p.focus('.vb-foot .vb-link')
await p.keyboard.press('Enter')
await p.waitForTimeout(900)
console.log('how open:', await p.evaluate(() => document.querySelector('dialog.vb-how')?.open), await root(p))
await p.screenshot({ path: `${out}/how_spikecount_1440.png` })
await p.click('.vb-step >> nth=1')
console.log('step read:', flat(await p.locator('.vb-step-read').innerText()))
await p.waitForTimeout(500)
await p.locator('.vb-step >> nth=1').scrollIntoViewIfNeeded()
await p.screenshot({ path: `${out}/how_mission_day30_1440.png` })
await p.click('.vb-step >> nth=0')
await p.waitForTimeout(500)
console.log('film edge after Preflight:', flat(await p.locator('.vb-edge').innerText()))
await p.screenshot({ path: `${out}/how_mission_preflight_1440.png` })
await p.keyboard.press('Escape')
await p.waitForTimeout(300)
console.log('how closed:', await p.evaluate(() => document.querySelector('dialog.vb-how')?.open), await root(p))
await p.click('.vb-spine >> nth=3')
await p.waitForTimeout(210)
await p.screenshot({ path: `${out}/slide_210ms_1440.png` })
await p.waitForTimeout(700)
console.log('spine ->', await root(p))
for (const m of ['tracktrace', 'bubblegrade', 'veinsqueeze', 'braindrift', 'garnmeter']) {
  await p.goto(base + m)
  await p.waitForTimeout(150)
  await ready(p)
  await p.waitForTimeout(500)
  await p.screenshot({ path: `${out}/preview_${m}_1440.png` })
}
await p.click('.vb-wordmark')
await p.waitForTimeout(900)
console.log('wordmark ->', await root(p))
await p.keyboard.press('Tab')
await p.keyboard.press('Tab')
await p.keyboard.press('Enter')
await p.waitForTimeout(900)
console.log('tab tab enter ->', await root(p))
await p.goto(base + 'home?how=1')
await p.waitForTimeout(300)
await ready(p)
await p.waitForTimeout(900)
await p.screenshot({ path: `${out}/how_home_1440.png` })

// ---- phone
p = await ctx(390, 844, true)
await p.goto(base + 'home')
await ready(p)
await p.waitForTimeout(2200)
await p.tap('[data-qa="primary"]')
await p.waitForTimeout(900)
console.log('phone home -> blood', await root(p))
await p.tap('[data-qa="primary"]')
await p.waitForTimeout(1200)
await p.screenshot({ path: `${out}/phone_running_390.png` })
await p.waitForSelector('.vb[data-state="result"]', { timeout: 20000 }).catch(() => logs.push('phone: no result'))
console.log('phone settled', await root(p), '|', flat(await p.locator('.vb-edge').innerText()))
await p.touchscreen.tap(160, 160)
await p.waitForTimeout(300)
console.log('phone cell tapped:', flat(await p.locator('.vb-loupe').innerText().catch(() => 'no loupe')))
await p.screenshot({ path: `${out}/loupe_tap_390.png` })
await p.tap('.vb-foot .vb-link')
await p.waitForTimeout(900)
await p.screenshot({ path: `${out}/how_spikecount_390.png` })
await p.tap('.vb-how-close')
await p.waitForTimeout(300)
await p.tap('.vb-sliver >> nth=4')
await p.waitForTimeout(900)
console.log('phone sliver ->', await root(p))
await p.screenshot({ path: `${out}/preview_braindrift_390.png` })
await p.tap('.vb-wordmark')
await p.waitForTimeout(900)
console.log('phone wordmark ->', await root(p))
console.log('phone horizontal overflow px:', await p.evaluate(() => document.documentElement.scrollWidth - window.innerWidth))
console.log(logs.length ? '--- console ---\n' + logs.join('\n') : 'no console errors')
await browser.close()
