// Dev-only: the real press at 1440 (idle, mid-hold, result). node src/protos/veinsqueeze_w1/_press.mjs <outDir>
import { chromium } from 'playwright-core'
const out = process.argv[2]
const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--hide-scrollbars', '--enable-unsafe-webgpu', '--use-angle=d3d11', '--autoplay-policy=no-user-gesture-required'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
page.on('pageerror', (e) => console.log('pageerror', e.message))
const t0 = Date.now()
await page.goto('http://localhost:5604/#/proto/veinsqueeze_w1/home', { waitUntil: 'load' })
await page.waitForSelector('.vsq-hold:not([aria-busy="true"]):not([aria-disabled="true"])', { timeout: 200000 }).catch(() => console.log('hold never enabled'))
console.log('enabled after', Date.now() - t0)
await page.waitForTimeout(800)
await page.screenshot({ path: `${out}/idle_1440.png` })
const box = await page.locator('.vsq-hold').boundingBox()
await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
await page.mouse.down()
await page.waitForTimeout(1900)
await page.screenshot({ path: `${out}/hold_1440.png` })
await page.mouse.up()
await page.waitForSelector('.vw1[data-state="result"]', { timeout: 200000 }).catch(() => console.log('never reached result'))
console.log('result after', Date.now() - t0)
await page.waitForTimeout(1500)
await page.screenshot({ path: `${out}/pressed_result_1440.png` })
console.log(await page.locator('.vw1-act').innerText())
await browser.close()
