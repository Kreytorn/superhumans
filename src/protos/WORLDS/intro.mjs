// Dev-only: frames of the opening move and of a hover. node src/protos/WORLDS/intro.mjs <outDir>
import { chromium } from 'playwright-core'
const [out] = process.argv.slice(2)
const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--hide-scrollbars'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 })
const logs = []
page.on('console', (m) => m.type() === 'error' && logs.push(m.text()))
page.on('pageerror', (e) => logs.push('[pageerror] ' + e.message))
await page.goto('http://localhost:5323/#/proto/WORLDS/home', { waitUntil: 'load' })
await page.waitForTimeout(900)
await page.screenshot({ path: `${out}/intro_a.jpg`, type: 'jpeg', quality: 85 })
await page.waitForSelector('.wd-root[data-ready="1"]', { timeout: 30000 })
await page.mouse.move(1180, 600)
await page.waitForTimeout(1500)
const fps = await page.evaluate(() => new Promise((res) => { let n = 0; const t0 = performance.now(); const f = () => { n++; if (performance.now() - t0 < 2000) requestAnimationFrame(f); else res(n / 2) }; requestAnimationFrame(f) }))
await page.screenshot({ path: `${out}/hover_brain.jpg`, type: 'jpeg', quality: 88 })
console.log('frames per second in headless (software) Edge:', fps)
// world to world
await page.goto('http://localhost:5323/#/proto/WORLDS/veinsqueeze', { waitUntil: 'load' })
await page.waitForSelector('.wd-page[data-open="1"]', { timeout: 30000 })
await page.waitForTimeout(800)
await page.screenshot({ path: `${out}/page_veinsqueeze_1440.jpg`, type: 'jpeg', quality: 88 })
await page.locator('.wd-next').click()
await page.waitForTimeout(1000)
await page.screenshot({ path: `${out}/next_mid.jpg`, type: 'jpeg', quality: 85 })
await page.waitForSelector('.wd-page[data-open="1"][data-id="braindrift"]', { timeout: 20000 })
await page.keyboard.press('Escape')
await page.waitForTimeout(2600)
console.log('after Escape:', await page.evaluate(() => location.hash))
if (logs.length) console.log([...new Set(logs)].slice(0, 8).join('\n'))
await browser.close()
